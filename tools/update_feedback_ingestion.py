def patch_fabric_feedback_query(expression: str) -> str:
    feedback_columns = (
        "Feedback Event Key",
        "Conversation Id",
        "Agent Id",
        "Channel",
        "Feedback Source",
        "Feedback Verdict",
        "Match Status",
    )

    def normalize_empty_table(match: re.Match) -> str:
        columns = re.findall(r'"([^"]+)"', match.group(1))
        deduplicated = list(dict.fromkeys(columns))
        for column in feedback_columns:
            if column not in deduplicated:
                deduplicated.append(column)
        encoded = ", ".join(json.dumps(column) for column in deduplicated)
        return f"EmptyTable({{{encoded}}})"

    expression = re.sub(
        r"EmptyTable\(\{([^}]*)\}\)",
        normalize_empty_table,
        expression,
    )
    rename_marker = '        {"Additional Metadata", "AdditionalMetadata"}'
    rename_block = '''        {"Additional Metadata", "AdditionalMetadata"},
        {"Feedback Event Key", "FeedbackEventKey"},
        {"Conversation Id", "ConversationId"},
        {"Agent Id", "AgentId"},
        {"Feedback Source", "FeedbackSource"},
        {"Feedback Verdict", "FeedbackVerdict"},
        {"Match Status", "MatchStatus"}'''
    if "FeedbackEventKey" not in expression:
        expression = expression.replace(rename_marker, rename_block, 1)
    selected_marker = '"AiAgentType"})'
    selected_replacement = (
        '"AiAgentType", "FeedbackEventKey", "ConversationId", "AgentId", "Channel", '
        '"FeedbackSource", "FeedbackVerdict", "MatchStatus"}, MissingField.UseNull)'
    )
    if '"FeedbackEventKey"' not in expression[expression.rfind("Selected =") :]:
        expression = expression.replace(selected_marker, selected_replacement, 1)
    return expression


def patch_fabric_pbit(source: Path, destination: Path) -> None:
    with zipfile.ZipFile(source, "r") as archive:
        infos = archive.infolist()
        parts = {info.filename: archive.read(info.filename) for info in infos}
    schema = json.loads(parts["DataModelSchema"].decode("utf-16-le"))
    model = schema["model"]
    table = next(table for table in model["tables"] if table["name"] == "ProductFeedback")
    source_obj = table["partitions"][0]["source"]
    original = source_obj["expression"]
    expression = "\n".join(original) if isinstance(original, list) else original
    expression = patch_fabric_feedback_query(expression)
    source_obj["expression"] = expression.splitlines() if isinstance(original, list) else expression
    add_model_columns(
        table,
        FEEDBACK_DIAGNOSTIC_COLUMNS,
        "https://github.com/microsoft/ESS/fabric-feedback",
    )
    parts["DataModelSchema"] = json.dumps(schema, ensure_ascii=False, separators=(",", ":")).encode("utf-16-le")
    raw = parts["UnappliedChanges"].decode("utf-16-le")
    raw = replace_query_text_raw(raw, "ProductFeedback", patch_fabric_feedback_query)
    json.loads(raw)
    parts["UnappliedChanges"] = raw.encode("utf-16-le")
    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED) as archive:
        for info in infos:
            archive.writestr(info, parts[info.filename])


