def add_model_columns(table: dict, columns: tuple[tuple[str, str], ...], namespace: str) -> None:
    existing = {column["name"] for column in table.get("columns", [])}
    for name, data_type in columns:
        if name in existing:
            continue
        table["columns"].append(
            {
                "name": name,
                "dataType": data_type,
                "sourceColumn": name,
                "lineageTag": str(uuid.uuid5(uuid.NAMESPACE_URL, f"{namespace}/{name}")),
                "summarizeBy": "none",
                "annotations": [{"name": "SummarizationSetBy", "value": "Automatic"}],
            }
        )


def set_partition_expression(model: dict, table_name: str, expression: str) -> None:
    table = next(table for table in model["tables"] if table["name"] == table_name)
    source = table["partitions"][0]["source"]
    original = source["expression"]
    source["expression"] = expression.splitlines() if isinstance(original, list) else expression


def rename_query_raw(raw: str, old_name: str, new_name: str) -> str:
    document = json.loads(raw)
    if any(item["name"] == new_name for item in document["queries"]):
        return raw
    if not any(item["name"] == old_name for item in document["queries"]):
        return raw
    old_encoded = '"name":' + json.dumps(old_name, ensure_ascii=False)
    new_encoded = '"name":' + json.dumps(new_name, ensure_ascii=False)
    position = raw.find(old_encoded)
    if position < 0:
        raise ValueError(f"Unapplied query name not found: {old_name}")
    return raw[:position] + new_encoded + raw[position + len(old_encoded) :]


def patch_direct_feedback_measures(model: dict) -> None:
    expressions = {
        ("Agent Performance", "Chat Thumbs Up Count"): (
            'CALCULATE(COUNTROWS(\'ConversationFeedback\'), '
            '\'ConversationFeedback\'[FeedbackType] = "Thumbs Up")'
        ),
        ("Agent Performance", "Chat Thumbs Down Count"): (
            'CALCULATE(COUNTROWS(\'ConversationFeedback\'), '
            '\'ConversationFeedback\'[FeedbackType] = "Thumbs Down")'
        ),
        ("Agent Performance", "Feedback Responses"): "COUNTROWS('ConversationFeedback')",
        ("Agent Performance", "Feedback Response Rate"): (
            "VAR MatchedFeedback =\n"
            "    CALCULATE(\n"
            "        DISTINCTCOUNT('ConversationFeedback'[ConversationId]),\n"
            "        KEEPFILTERS(\n"
            "            'ConversationFeedback'[MatchStatus] IN "
            "{\"Native transcript\", \"Exact conversation match\"}\n"
            "        )\n"
            "    )\n"
            "RETURN DIVIDE(MatchedFeedback, [Conversations], 0)"
        ),
        ("ConversationFeedback", "Total Feedback"): "COUNTROWS('ConversationFeedback')",
        ("ConversationFeedback", "Thumbs Up Count"): (
            'CALCULATE(COUNTROWS(\'ConversationFeedback\'), '
            '\'ConversationFeedback\'[FeedbackType] = "Thumbs Up")'
        ),
        ("ConversationFeedback", "Thumbs Down Count"): (
            'CALCULATE(COUNTROWS(\'ConversationFeedback\'), '
            '\'ConversationFeedback\'[FeedbackType] = "Thumbs Down")'
        ),
        ("ConversationFeedback", "Satisfaction Rate"): (
            "DIVIDE(\n"
            "    CALCULATE(COUNTROWS('ConversationFeedback'), "
            "'ConversationFeedback'[FeedbackType] = \"Thumbs Up\"),\n"
            "    CALCULATE(COUNTROWS('ConversationFeedback'), "
            "'ConversationFeedback'[FeedbackType] IN {\"Thumbs Up\", \"Thumbs Down\"}),\n"
            "    0\n"
            ")"
        ),
        ("ConversationFeedback", "Thumbs Up Rate"): (
            "DIVIDE(\n"
            "    CALCULATE(COUNTROWS('ConversationFeedback'), "
            "'ConversationFeedback'[FeedbackType] = \"Thumbs Up\"),\n"
            "    CALCULATE(COUNTROWS('ConversationFeedback'), "
            "'ConversationFeedback'[FeedbackType] IN {\"Thumbs Up\", \"Thumbs Down\"}),\n"
            "    BLANK()\n"
            ")"
        ),
    }
    for (table_name, measure_name), expression in expressions.items():
        table = next(table for table in model["tables"] if table["name"] == table_name)
        measure = next(
            (measure for measure in table.get("measures", []) if measure["name"] == measure_name),
            None,
        )
        if measure is None:
            raise ValueError(f"Feedback measure not found: {table_name}[{measure_name}]")
        measure["expression"] = expression


def patch_direct_pbit(source: Path, destination: Path) -> None:
    external_query = build_external_feedback_query()
    feedback_query = build_conversation_feedback_query()
    with zipfile.ZipFile(source, "r") as archive:
        infos = archive.infolist()
        parts = {info.filename: archive.read(info.filename) for info in infos}

    schema = json.loads(parts["DataModelSchema"].decode("utf-16-le"))
    model = schema["model"]
    old_parameter = next(
        (item for item in model["expressions"] if item["name"] == OLD_FEEDBACK_PARAMETER),
        None,
    )
    if old_parameter and not any(
        item["name"] == FEEDBACK_PARAMETER for item in model["expressions"]
    ):
        old_parameter["name"] = FEEDBACK_PARAMETER
    upsert_expression(
        model,
        {
            "name": FEEDBACK_PARAMETER,
            "description": FEEDBACK_PARAMETER_DESCRIPTION,
            "kind": "m",
            "expression": FEEDBACK_PARAMETER_EXPRESSION,
            "lineageTag": FEEDBACK_PARAMETER_LINEAGE,
            "annotations": [
                {"name": "PBI_NavigationStepName", "value": "Navigation"},
                {"name": "PBI_ResultType", "value": "Text"},
            ],
        },
        "TopicRules",
    )
    upsert_expression(
        model,
        {
            "name": FEEDBACK_QUERY,
            "kind": "m",
            "expression": external_query,
            "lineageTag": FEEDBACK_QUERY_LINEAGE,
            "annotations": [{"name": "PBI_ResultType", "value": "List"}],
        },
        "TopicRules",
    )
    set_partition_expression(model, "ConversationFeedback", feedback_query)
    patch_direct_feedback_measures(model)
    feedback_table = next(table for table in model["tables"] if table["name"] == "ConversationFeedback")
    add_model_columns(
        feedback_table,
        FEEDBACK_DIAGNOSTIC_COLUMNS,
        "https://github.com/microsoft/ESS/feedback",
    )
    parts["DataModelSchema"] = json.dumps(schema, ensure_ascii=False, separators=(",", ":")).encode("utf-16-le")

    raw = parts["UnappliedChanges"].decode("utf-16-le")
    raw = rename_query_raw(raw, OLD_FEEDBACK_PARAMETER, FEEDBACK_PARAMETER)
    raw = insert_query_raw(
        raw,
        {
            "name": FEEDBACK_PARAMETER,
            "lineageTag": FEEDBACK_PARAMETER_LINEAGE,
            "description": FEEDBACK_PARAMETER_DESCRIPTION,
            "navigationStepName": "Navigation",
            "text": [FEEDBACK_PARAMETER_EXPRESSION],
            "loadAsTableDisabled": True,
            "resultType": "Text",
            "isHidden": False,
        },
    )
    raw = insert_query_raw(
        raw,
        {
            "name": FEEDBACK_QUERY,
            "lineageTag": FEEDBACK_QUERY_LINEAGE,
            "text": external_query.splitlines(),
            "loadAsTableDisabled": True,
            "resultType": "List",
            "isHidden": False,
        },
    )
    raw = replace_query_text_raw(raw, FEEDBACK_PARAMETER, lambda _: FEEDBACK_PARAMETER_EXPRESSION)
    raw = replace_query_text_raw(raw, FEEDBACK_QUERY, lambda _: external_query)
    raw = replace_query_text_raw(raw, "ConversationFeedback", lambda _: feedback_query)
    json.loads(raw)
    parts["UnappliedChanges"] = raw.encode("utf-16-le")

    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED) as archive:
        for info in infos:
            archive.writestr(info, parts[info.filename])


