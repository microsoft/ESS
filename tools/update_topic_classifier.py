def build_classifier() -> str:
    return f'''let
{build_normalization()}
    Rules = List.Buffer(List.Transform(Table.ToRecords(TopicRules), (rule) =>
        let
            keywords = NormalizeTerms(rule[Keywords]),
            exclusions = NormalizeTerms(rule[Exclusions])
        in
            if List.IsEmpty(keywords) then error "Topic rule has no Keywords after normalization."
            else Record.TransformFields(rule, {{{{"Locale", RuleLocale}}, {{"Keywords", each keywords}}, {{"Exclusions", each exclusions}}}}))),
    ClassifierVersion = {m_string(CLASSIFIER_VERSION)},

    ContainsTerm = (normalizedText as text, term as text, language as text) as logical =>
        let
            normalizedTerm = term
        in
            if normalizedTerm = "" then false
            else if language = "zh" then Text.Contains(normalizedText, normalizedTerm, Comparer.OrdinalIgnoreCase)
            else Text.Contains(" " & normalizedText & " ", " " & normalizedTerm & " ", Comparer.OrdinalIgnoreCase),

    TermWeight = (term as text, language as text) as number =>
        let
            normalizedTerm = term,
            wordCount = List.Count(List.Select(Text.Split(normalizedTerm, " "), each _ <> ""))
        in
            if language = "zh" then (if Text.Length(normalizedTerm) >= 4 then 3 else 2)
            else if wordCount >= 2 then 3
            else if Text.Length(normalizedTerm) <= 2 then 1
            else 2,

    ClassifyTopic = (inputText as nullable text, optional inputLocale as nullable text) as record =>
        let
            normalizedText = NormalizeText(inputText),
            language = LocalePrefix(inputLocale),
            eligibleRules = List.Select(Rules, each [Locale] = "*" or [Locale] = language),
            scoredRules = List.Transform(
                eligibleRules,
                (rule) =>
                    let
                        keywords = rule[Keywords],
                        exclusions = rule[Exclusions],
                        hits = List.Select(keywords, each ContainsTerm(normalizedText, _, language)),
                        excluded = List.AnyTrue(List.Transform(exclusions, each ContainsTerm(normalizedText, _, language))),
                        score = if excluded then 0 else List.Sum(List.Transform(hits, each TermWeight(_, language))),
                        sourceRank =
                            if rule[RuleOrigin] = "CustomerExplicit" then 4
                            else if rule[RuleOrigin] = "CustomerSaved" then 3
                            else if rule[RuleOrigin] = "NativeLearned" then 2
                            else if rule[RuleOrigin] = "SemanticLearned" then 1
                            else 0
                    in
                        [Rule = rule, Hits = hits, Score = score, SourceRank = sourceRank]
            ),
            positiveRules = List.Select(scoredRules, each [Score] > 0),
            sortedRules = List.Sort(
                positiveRules,
                (left, right) =>
                    if left[SourceRank] > right[SourceRank] then -1
                    else if left[SourceRank] < right[SourceRank] then 1
                    else if left[Score] > right[Score] then -1
                    else if left[Score] < right[Score] then 1
                    else if left[Rule][Priority] > right[Rule][Priority] then -1
                    else if left[Rule][Priority] < right[Rule][Priority] then 1
                    else Value.Compare(left[Rule][CanonicalTopic], right[Rule][CanonicalTopic])
            ),
            top = List.First(sortedRules, null),
            topSourceRank = if top = null then null else top[SourceRank],
            topScore = if top = null then 0 else top[Score],
            topPriority = if top = null then null else top[Rule][Priority],
            tiedRules = if top = null then {{}} else List.Select(
                sortedRules,
                each [SourceRank] = topSourceRank and [Score] = topScore and [Rule][Priority] = topPriority
            ),
            tiedTopics = List.Distinct(List.Transform(
                tiedRules,
                each [Rule][Vertical] & "|" & [Rule][CanonicalTopic]
            )),
            ambiguous = List.Count(tiedTopics) > 1,
            chosen = if ambiguous then null else top,
            ruleSource = if chosen = null then null else chosen[Rule][RuleSource],
            resultVersion =
                if ruleSource = "Customer" then ClassifierVersion & "+CUSTOMER"
                else ClassifierVersion,
            confidence =
                if chosen = null then (if ambiguous then 0.4 else 0.0)
                else if topScore >= 6 then 0.98
                else if topScore >= 4 then 0.93
                else if topScore >= 2 then 0.85
                else 0.70,
            result =
                if normalizedText = "" then [
                    Topic = "No User Intent",
                    Vertical = "System-Init",
                    MatchedTerms = null,
                    Score = 0.0,
                    Confidence = 1.0,
                    Ambiguous = false,
                    Language = language,
                    RuleSource = "",
                    ClassifierVersion = ClassifierVersion
                ]
                else if chosen = null then [
                    Topic = "Other / Uncategorized",
                    Vertical = "Unknown",
                    MatchedTerms = if ambiguous then Text.Combine(
                        List.Distinct(List.Combine(List.Transform(tiedRules, each [Hits]))),
                        " | "
                    ) else null,
                    Score = Number.From(topScore),
                    Confidence = confidence,
                    Ambiguous = ambiguous,
                    Language = language,
                    RuleSource = "",
                    ClassifierVersion = ClassifierVersion
                ]
                else [
                    Topic = chosen[Rule][CanonicalTopic],
                    Vertical = chosen[Rule][Vertical],
                    MatchedTerms = Text.Combine(chosen[Hits], " | "),
                    Score = Number.From(chosen[Score]),
                    Confidence = confidence,
                    Ambiguous = false,
                    Language = language,
                    RuleSource = ruleSource,
                    ClassifierVersion = resultVersion
                ]
        in
            result
in
    ClassifyTopic
'''


